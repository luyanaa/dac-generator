#!/usr/bin/env python3
"""Signoff for the sky130 5 V dump-tail video DAC array.

    ./signoff.py                  # build + drc + lvs + pins + pex
    ./signoff.py --stage drc
    ./signoff.py --selftest       # prove the gates reject mutations

The array is the P5 cell in `../video`, on sky130A: 255 identical dump-tail
cells plus the two-device replica, 1022 devices (512 pfet, 510 nfet).  The
devices are the PDK's 5 V `g5v0d10v5` pfet/nfet at W/L 8/0.5, generated by
magic's `gencell` (`gen_devices.py`); the array is drawn by `gen_gds.py`.

Gates:
  build  generate devices + the flattened top; the generator's own short
         check must pass.
  drc    KLayout `sky130A_mr.drc`, feol+beol, top `dac_video_ana`; 0 items.
  lvs    Magic flat extraction.  The contract is a walk from the two pads,
         independent of Magic's node names and of D/S orientation (the MOS is
         symmetric): pad -> nfet -> shared tail -> cascode -> mirror -> vdd.
         The pfet bulk must be vdd (the guard ring taps are tied by met1 bars),
         the nfet bulk VSUBS.
  pins   The 510 met2 pads are measured on the drawn GDS on an exact 3.75 um
         grid inside the 7.5 um cell pitch, with their d_/db_ labels.
  pex    hierarchical extraction, cthresh/rthresh 0: 1022 instances, the
         per-net capacitance and no floating node.

Not claimed: the digital macro, the wrapper, the output pad/ESD, and the
100 pF vcp capacitor (a wrapper requirement; the benchtop models it).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
GDS = BUILD / "video_sky130.gds"
MAGIC_DIR = BUILD / "magic"
TOP = "dac_video_ana"

KLAYOUT_BUILD = "/usr/bin/klayout"
KLAYOUT_DECK = "/nix/store/1whjbzm6gw6l4h0sjxdv92lyw7lq1ar8-klayout-0.30.12/bin/klayout"

PIN_PITCH_UM = 3.75
PIN_X0_UM = 2.25
PIN_Y_UM = (-18.20, -17.80)
PIN_W_UM = 0.60

ANALOG_PORTS = ("vdd", "vss", "vbp", "vcp", "iout", "idump")
PFET = "sky130_fd_pr__pfet_g5v0d10v5"
NFET = "sky130_fd_pr__nfet_g5v0d10v5"
W_UM, L_UM = 8.0, 0.5
N_CELLS = 255


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def run(cmd, cwd=None, env=None, timeout=3600):
    proc = subprocess.run([str(c) for c in cmd], cwd=cwd, env=env,
                          capture_output=True, text=True, timeout=timeout)
    return proc


def find_pdk() -> Path:
    base = Path.home() / ".ciel/ciel/sky130/versions"
    hits = sorted(p for p in base.iterdir()
                  if (p / "sky130A/libs.tech/magic").is_dir())
    if not hits:
        die(f"no sky130A install under {base}")
    return hits[-1]


def magicrc(pdk: Path) -> Path:
    return pdk / "sky130A/libs.tech/magic/sky130A.magicrc"


def magic_tech(pdk: Path) -> Path:
    return pdk / "sky130A/libs.tech/magic"


def cell_tags() -> list[str]:
    tags = []
    for j in range(N_CELLS):
        k = 0
        while j >= 2 ** (k + 1) - 1:
            k += 1
        tags.append(f"b{k}_{j - (2 ** k - 1)}")
    return tags


def build() -> dict:
    if not Path(KLAYOUT_BUILD).is_file():
        die(f"{KLAYOUT_BUILD} missing")
    BUILD.mkdir(parents=True, exist_ok=True)
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "gen_devices.py"], cwd=ROOT)
    (BUILD / "gen_devices.log").write_text(p.stdout + p.stderr)
    if p.returncode:
        die("device generation failed (see build/gen_devices.log)")
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "gen_gds.py",
             "-rd", f"out={GDS}"], cwd=ROOT)
    (BUILD / "gen.log").write_text(p.stdout + p.stderr)
    if p.returncode:
        die("array generation failed or reported a short (see build/gen.log)")
    return {"ok": True, "log": str(BUILD / "gen.log"),
            "note": (p.stdout + p.stderr).strip().splitlines()[-1]}


def drc(pdk: Path) -> dict:
    deck = (pdk / "sky130A/libs.tech/klayout/drc/sky130A_mr.drc")
    rdb = BUILD / "drc.lyrdb"
    if rdb.exists():
        rdb.unlink()
    p = run([KLAYOUT_DECK, "-b", "-r", deck,
             "-rd", f"input={GDS}", "-rd", f"report={rdb}",
             "-rd", f"topcell={TOP}", "-rd", "thr=4",
             "-rd", "feol=true", "-rd", "beol=true"], timeout=7200)
    (BUILD / "drc.log").write_text(p.stdout + p.stderr)
    if p.returncode or not rdb.is_file():
        die("KLayout DRC did not produce a report (see build/drc.log)")
    import xml.etree.ElementTree as ET
    root = ET.parse(rdb).getroot()
    items = root.findall("./items/item")
    cats = Counter((it.findtext("category") or "").strip("'") for it in items)
    return {"ok": not items, "items": len(items),
            "cells": len(root.findall("./cells/cell")),
            "categories": dict(cats.most_common()),
            "log": str(BUILD / "drc.log")}


def magic(pdk: Path, name: str, body: str, timeout=3600) -> Path:
    MAGIC_DIR.mkdir(parents=True, exist_ok=True)
    tcl = MAGIC_DIR / name
    tcl.write_text(body)
    env = dict(os.environ)
    env["PDK_ROOT"] = str(pdk)
    env["MAGIC_TECH_PATH"] = str(magic_tech(pdk))
    p = run(["magic", "-dnull", "-noconsole", "-rcfile", magicrc(pdk),
             tcl], cwd=MAGIC_DIR, env=env, timeout=timeout)
    log = MAGIC_DIR / (tcl.stem + ".log")
    log.write_text(p.stdout + p.stderr)
    for ext in MAGIC_DIR.glob("*.ext"):
        ext.unlink()
    if p.returncode:
        die(f"magic {name} failed (see {log})")
    return log


def read_top() -> str:
    return (f"gds read {GDS.with_suffix('')}\n"
            f"load {TOP}\n"
            "select top cell\n")


def parse_flat(txt: str):
    devs = []
    for ln in txt.splitlines():
        s = ln.strip()
        if not s.startswith("X"):
            continue
        f = s.split()
        if len(f) < 6:
            continue
        params = dict(t.split("=", 1) for t in f[6:] if "=" in t)
        devs.append((f[0], f[1:5], f[5], params))
    return devs


def check(devs) -> tuple[list[str], dict]:
    problems: list[str] = []
    tags = cell_tags()
    pad_nets = {"d_" + t for t in tags} | {"db_" + t for t in tags}
    rails = set(ANALOG_PORTS)
    allnets: set[str] = set()

    def num(tok):
        m = re.match(r"^([-+0-9.eE]+)([a-zA-Z]*)$", tok)
        if not m:
            return None
        v = float(m.group(1))
        return v * {"": 1, "u": 1, "m": 1e-3, "k": 1e3}.get(m.group(2), 1)

    mirror: dict[str, str] = {}     # md -> vdd (gate vbp)
    cascode: dict[str, str] = {}    # tail -> md (gate vcp)
    diode_m = diode_c = 0
    for name, nodes, sub, params in devs:
        d, g, s, b = nodes
        t = {d, s}
        allnets.update(nodes)
        w, l = params.get("w"), params.get("l")
        if w is None or l is None:
            problems.append(f"{name}: missing w/l")
            continue
        wv, lv = num(w), num(l)
        if wv is None or lv is None or abs(wv - W_UM) > 1e-6 or abs(lv - L_UM) > 1e-6:
            problems.append(f"{name}: {w}/{l} um, want {W_UM:g}/{L_UM:g}")
        if sub == PFET:
            if b != "vdd":
                problems.append(f"{name}: pfet bulk {b}, want vdd")
            if g == "vbp":
                if "vbp" in t:
                    diode_m += 1
                    if t != {"vdd", "vbp"}:
                        problems.append(f"{name}: replica mirror terminals {t}, "
                                        f"want vdd+vbp")
                else:
                    if "vdd" not in t or len(t) != 2:
                        problems.append(f"{name}: mirror terminals {t}, want "
                                        f"vdd + an internal node")
                        continue
                    md = (t - {"vdd"}).pop()
                    if md in rails or md in pad_nets:
                        problems.append(f"{name}: mirror internal {md} is a "
                                        f"rail/pad")
                    mirror[md] = name
            elif g == "vcp":
                if "vcp" in t:
                    diode_c += 1
                    if t != {"vbp", "vcp"}:
                        problems.append(f"{name}: replica cascode terminals "
                                        f"{t}, want vbp+vcp")
                else:
                    if len(t) != 2:
                        problems.append(f"{name}: cascode terminals {t}")
                        continue
                    for n in t:
                        if n in rails or n in pad_nets:
                            problems.append(f"{name}: cascode terminal {n} is a "
                                            f"rail/pad")
                    a, bb = sorted(t)
                    cascode[a] = bb
                    cascode[bb] = a
            else:
                problems.append(f"{name}: pfet gate {g}, want vbp/vcp")
        elif sub == NFET:
            if b not in ("VSUBS", "vss"):
                problems.append(f"{name}: nfet bulk {b}, want VSUBS/vss")
            if g not in pad_nets:
                problems.append(f"{name}: nfet gate {g} is not a pad")
            if len(t) != 2:
                problems.append(f"{name}: pair terminals {t}")
                continue
            drains = t & {"iout", "idump"}
            if len(drains) != 1:
                problems.append(f"{name}: pair drain set {t}, want one of "
                                f"iout/idump")
            if g in pad_nets and drains:
                tails = t - drains
                if len(tails) == 1:
                    tail = tails.pop()
                    if tail in rails or tail in pad_nets:
                        problems.append(f"{name}: tail {tail} is a rail/pad")
                    cascode.setdefault("tail:" + tail, name)
        else:
            problems.append(f"{name}: unexpected device {sub}")

    n_p = sum(1 for d in devs if d[2] == PFET)
    n_n = sum(1 for d in devs if d[2] == NFET)
    if len(devs) != 1022 or n_p != 512 or n_n != 510:
        problems.append(f"{len(devs)} devices ({n_p} pfet, {n_n} nfet), want "
                        f"1022 (512/510)")
    if diode_m != 1 or diode_c != 1:
        problems.append(f"{diode_m} replica mirrors, {diode_c} replica "
                        f"cascodes, want 1/1")

    gate = {}
    for name, nodes, sub, params in devs:
        if sub != NFET:
            continue
        d, g, s, b = nodes
        t = {d, s}
        dn = (t & {"iout", "idump"})
        if len(t) == 2 and len(dn) == 1 and g in pad_nets:
            gate[g] = ((t - dn).pop(), dn.pop())
    if len(gate) != 2 * N_CELLS:
        problems.append(f"{len(gate)} pad gates, want {2 * N_CELLS}")
    used_mirror = set()
    for tag in tags:
        a, bb = "d_" + tag, "db_" + tag
        if a not in gate or bb not in gate:
            problems.append(f"{tag}: a pad has no switch gate")
            continue
        ta, da = gate[a]
        tb, db_ = gate[bb]
        if da != "iout":
            problems.append(f"{a}: drain {da}, want iout")
        if db_ != "idump":
            problems.append(f"{bb}: drain {db_}, want idump")
        if ta != tb:
            problems.append(f"{tag}: the pair's tails differ ({ta} vs {tb})")
            continue
        md = cascode.get(ta)
        if md is None:
            problems.append(f"{tag}: tail {ta} is not a cascode terminal")
            continue
        if md not in mirror:
            problems.append(f"{tag}: cascode terminal {md} is not a mirror "
                            f"terminal")
            continue
        used_mirror.add(md)
    if len(used_mirror) != N_CELLS:
        problems.append(f"{len(used_mirror)} mirrors used by cells, want "
                        f"{N_CELLS}")
    if len(mirror) != N_CELLS:
        problems.append(f"{len(mirror)} cell mirrors, want {N_CELLS}")

    want_nets = (len(rails) + len(pad_nets) + 2 * N_CELLS
                 + (1 if "VSUBS" in allnets else 0))
    if len(allnets) != want_nets:
        problems.append(f"{len(allnets)} nets, want {want_nets} "
                        f"(6 rails + 510 pads + 2 internal/cell + VSUBS)")
    return problems, {"devices": len(devs), "pfet": n_p, "nfet": n_n,
                      "nets": len(allnets), "mirrors": len(mirror),
                      "cascodes": len(cascode) // 2}


def lvs(pdk: Path) -> dict:
    spice = MAGIC_DIR / "lvs.spice"
    magic(pdk, "extract_lvs.tcl",
          read_top() +
          "port makeall\n"
          "extract\n"
          "ext2spice hierarchy off\n"
          "ext2spice subcircuits off\n"
          f"ext2spice -o {spice}\n"
          f"puts LVS_DONE\n"
          "quit -noprompt\n")
    txt = spice.read_text()
    if "LVS_DONE" not in (MAGIC_DIR / "extract_lvs.log").read_text():
        die("magic LVS did not finish")
    devs = parse_flat(txt)
    problems, stats = check(devs)
    return {"ok": not problems, "problems": problems[:20], **stats,
            "spice": str(spice)}


def pins() -> dict:
    out = BUILD / "pinplan.json"
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "pinplan.py",
             "-rd", f"gds={GDS}", "-rd", f"out={out}"])
    if p.returncode or not out.is_file():
        print(p.stdout + p.stderr, file=sys.stderr)
        die("pinplan extraction failed")
    plan = json.loads(out.read_text())
    y0, y1 = PIN_Y_UM
    pads = [s for s in plan["shapes"]
            if s["layer"] == "m2"
            and abs(s["y1"] - y0) < 1e-3 and abs(s["y2"] - y1) < 1e-3]
    pads.sort(key=lambda s: (s["x1"] + s["x2"]) / 2)
    problems = []
    if len(pads) != 2 * N_CELLS:
        problems.append(f"{len(pads)} pads at y {PIN_Y_UM}, want {2 * N_CELLS}")
    for j in range(min(len(pads), 2 * N_CELLS)):
        want_x = (j // 2) * 2 * PIN_PITCH_UM + PIN_X0_UM + (j % 2) * PIN_PITCH_UM
        cx = (pads[j]["x1"] + pads[j]["x2"]) / 2
        w = pads[j]["x2"] - pads[j]["x1"]
        if abs(cx - want_x) > 1e-3 or abs(w - PIN_W_UM) > 1e-3:
            problems.append(f"pad {j}: x {pads[j]['x1']:.3f}..{pads[j]['x2']:.3f}"
                            f", want centre {want_x:.3f} width {PIN_W_UM}")
            if len(problems) > 8:
                break
    labels = {l["net"] for l in plan["labels"]}
    want_labels = ({"d_" + t for t in cell_tags()}
                   | {"db_" + t for t in cell_tags()})
    missing = want_labels - labels
    if missing:
        problems.append(f"{len(missing)} pad labels missing, e.g. "
                        f"{sorted(missing)[:3]}")
    for p_ in ANALOG_PORTS:
        if p_ not in labels:
            problems.append(f"rail label {p_} missing")
    return {"ok": not problems, "pads": len(pads),
            "labels": len(labels), "problems": problems[:10]}


def pex(pdk: Path) -> dict:
    spice = MAGIC_DIR / "pex.spice"
    magic(pdk, "extract_pex.tcl",
          read_top() +
          "extract\n"
          "ext2spice hierarchy on\n"
          "ext2spice cthresh 0\n"
          "ext2spice rthresh 0\n"
          f"ext2spice -o {spice}\n"
          "puts PEX_DONE\n"
          "quit -noprompt\n", timeout=7200)
    txt = spice.read_text()
    x = [ln for ln in txt.splitlines() if ln.strip().startswith("X")]
    caps = [ln for ln in txt.splitlines() if ln.strip().startswith("C")]
    floating = [ln for ln in txt.splitlines() if "**FLOATING" in ln]
    total = 0.0
    for ln in caps:
        f = ln.split()
        try:
            v = f[3]
            m = re.match(r"^([-+0-9.eE]+)([fpnumk]?)", v)
            total += float(m.group(1)) * {"f": 1e-15, "p": 1e-12,
                                          "n": 1e-9, "u": 1e-6,
                                          "m": 1e-3, "": 1}[m.group(2)]
        except Exception:
            pass
    ok = len(x) == 1022 and not floating
    return {"ok": ok, "instances": len(x), "caps": len(caps),
            "cap_ff": round(total * 1e15, 1), "floating": len(floating),
            "spice": str(spice)}


def selftest() -> int:
    """Mutate the extracted netlist and prove the contract rejects it."""
    spice = MAGIC_DIR / "lvs.spice"
    if not spice.is_file():
        die("no build/magic/lvs.spice; run --stage lvs first")
    devs = parse_flat(spice.read_text())
    problems, _ = check(devs)
    if problems:
        print("baseline fails:", problems[:3])
        return 1

    def mutated(fn):
        d = [(n, list(nodes), s, dict(p)) for n, nodes, s, p in devs]
        fn(d)
        return check(d)[0]

    tests = []
    def swap_pad_gate(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == NFET and nodes[1].startswith("d_"):
                nodes[1] = "d_b0_0"       # duplicate gate
                break
    tests.append(("duplicate pad gate", swap_pad_gate))
    def open_tail(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == NFET:
                nodes[2] = "floating_tail"
                d[i] = (n, nodes, s, p)
                break
    tests.append(("open tail", open_tail))
    def pfet_bulk(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == PFET:
                nodes[3] = "vss"
                break
    tests.append(("pfet bulk vss", pfet_bulk))
    bad = []
    for name, fn in tests:
        if not mutated(fn):
            bad.append(name)
    print(f"selftest: {len(tests) - len(bad)}/{len(tests)} mutations rejected")
    if bad:
        print("NOT rejected:", bad)
        return 1
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all",
                    choices=["all", "build", "drc", "lvs", "pins", "pex"])
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    pdk = find_pdk()
    report = {}
    stages = (["build", "drc", "lvs", "pins", "pex"] if a.stage == "all"
              else [a.stage])
    rc = 0
    for st in stages:
        fn = {"build": build, "drc": drc, "lvs": lvs,
              "pins": pins, "pex": pex}[st]
        try:
            res = build() if st == "build" else (pins() if st == "pins"
                                                 else fn(pdk))
        except SystemExit:
            raise
        report[st] = res
        print(json.dumps({st: res}, indent=2)[:1600])
        if not res.get("ok", True):
            rc = 1
    (BUILD / "signoff.json").write_text(json.dumps(report, indent=2))
    return rc


if __name__ == "__main__":
    sys.exit(main())
