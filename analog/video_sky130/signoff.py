#!/usr/bin/env python3
"""Signoff for the sky130 5 V dump-tail video DAC array.

    ./signoff.py                  # build + drc + lvs + pins + pex
    ./signoff.py --stage drc
    ./signoff.py --selftest       # prove the gates reject mutations

The array is the P5 cell in `../video`, on sky130A: 255 identical dump-tail
cells plus the two-device replica, 1022 devices (512 pfet, 510 nfet).  The
devices are the PDK's 5 V `g5v0d10v5` pfet/nfet at W/L 8/0.5, generated by
magic's `gencell` (`gen_devices.py`); the array is drawn by `gen_gds.py`.

Gates:
  build  generate devices + the flattened top; the generator's own short
         check must pass.
  drc    KLayout `sky130A_mr.drc`, feol+beol, top `dac_video_ana`; 0 items.
  lvs    Magic flat extraction.  The contract is a walk from the two pads,
         independent of Magic's node names and of D/S orientation (the MOS is
         symmetric): pad -> nfet -> shared tail -> cascode -> mirror -> vdd.
         The pfet bulk must be vdd (the guard ring taps are tied by met1 bars),
         the nfet bulk VSUBS.
  pins   The 510 met2 pads are measured on the drawn GDS on an exact 3.75 um
         grid inside the 7.5 um cell pitch, with their d_/db_ labels.
  pex    hierarchical extraction, cthresh/rthresh 0: 1022 instances, the
         per-net capacitance and no floating node.

Not claimed: the digital macro, the wrapper, the output pad/ESD, and the
100 pF vcp capacitor (a wrapper requirement; the benchtop models it).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
GDS = BUILD / "video_sky130.gds"
MAGIC_DIR = BUILD / "magic"
TOP = "dac_video_ana"

KLAYOUT_BUILD = "/usr/bin/klayout"
KLAYOUT_DECK = "/nix/store/1whjbzm6gw6l4h0sjxdv92lyw7lq1ar8-klayout-0.30.12/bin/klayout"

PIN_PITCH_UM = 3.75
PIN_X0_UM = 2.25
PIN_Y_UM = (-18.20, -17.80)
PIN_W_UM = 0.60

ANALOG_PORTS = ("vdd", "vss", "vbp", "vcp", "iout", "idump")
PFET = "sky130_fd_pr__pfet_g5v0d10v5"
NFET = "sky130_fd_pr__nfet_g5v0d10v5"
W_UM, L_UM = 8.0, 0.5
N_CELLS = 255


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def run(cmd, cwd=None, env=None, timeout=3600):
    proc = subprocess.run([str(c) for c in cmd], cwd=cwd, env=env,
                          capture_output=True, text=True, timeout=timeout)
    return proc


def find_pdk() -> Path:
    base = Path.home() / ".ciel/ciel/sky130/versions"
    hits = sorted(p for p in base.iterdir()
                  if (p / "sky130A/libs.tech/magic").is_dir())
    if not hits:
        die(f"no sky130A install under {base}")
    return hits[-1]


def magicrc(pdk: Path) -> Path:
    return pdk / "sky130A/libs.tech/magic/sky130A.magicrc"


def magic_tech(pdk: Path) -> Path:
    return pdk / "sky130A/libs.tech/magic"


def cell_bit(j: int) -> int:
    k = 0
    while j >= 2 ** (k + 1) - 1:
        k += 1
    return k


def cell_tags() -> list[str]:
    return [f"b{cell_bit(j)}_{j - (2 ** cell_bit(j) - 1)}"
            for j in range(N_CELLS)]


def build() -> dict:
    if not Path(KLAYOUT_BUILD).is_file():
        die(f"{KLAYOUT_BUILD} missing")
    BUILD.mkdir(parents=True, exist_ok=True)
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "gen_devices.py"], cwd=ROOT)
    (BUILD / "gen_devices.log").write_text(p.stdout + p.stderr)
    if p.returncode:
        die("device generation failed (see build/gen_devices.log)")
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "gen_gds.py",
             "-rd", f"out={GDS}"], cwd=ROOT)
    (BUILD / "gen.log").write_text(p.stdout + p.stderr)
    if p.returncode:
        die("array generation failed or reported a short (see build/gen.log)")
    return {"ok": True, "log": str(BUILD / "gen.log"),
            "note": (p.stdout + p.stderr).strip().splitlines()[-1]}


def drc(pdk: Path) -> dict:
    deck = (pdk / "sky130A/libs.tech/klayout/drc/sky130A_mr.drc")
    rdb = BUILD / "drc.lyrdb"
    if rdb.exists():
        rdb.unlink()
    p = run([KLAYOUT_DECK, "-b", "-r", deck,
             "-rd", f"input={GDS}", "-rd", f"report={rdb}",
             "-rd", f"topcell={TOP}", "-rd", "thr=4",
             "-rd", "feol=true", "-rd", "beol=true"], timeout=7200)
    (BUILD / "drc.log").write_text(p.stdout + p.stderr)
    if p.returncode or not rdb.is_file():
        die("KLayout DRC did not produce a report (see build/drc.log)")
    import xml.etree.ElementTree as ET
    root = ET.parse(rdb).getroot()
    items = root.findall("./items/item")
    cats = Counter((it.findtext("category") or "").strip("'") for it in items)
    return {"ok": not items, "items": len(items),
            "cells": len(root.findall("./cells/cell")),
            "categories": dict(cats.most_common()),
            "log": str(BUILD / "drc.log")}


def magic(pdk: Path, name: str, body: str, timeout=3600) -> Path:
    MAGIC_DIR.mkdir(parents=True, exist_ok=True)
    tcl = MAGIC_DIR / name
    tcl.write_text(body)
    env = dict(os.environ)
    env["PDK_ROOT"] = str(pdk)
    env["MAGIC_TECH_PATH"] = str(magic_tech(pdk))
    p = run(["magic", "-dnull", "-noconsole", "-rcfile", magicrc(pdk),
             tcl], cwd=MAGIC_DIR, env=env, timeout=timeout)
    log = MAGIC_DIR / (tcl.stem + ".log")
    log.write_text(p.stdout + p.stderr)
    for ext in MAGIC_DIR.glob("*.ext"):
        ext.unlink()
    if p.returncode:
        die(f"magic {name} failed (see {log})")
    return log


def read_top() -> str:
    return (f"gds read {GDS.with_suffix('')}\n"
            f"load {TOP}\n"
            "select top cell\n")


def parse_flat(txt: str):
    devs = []
    for ln in txt.splitlines():
        s = ln.strip()
        if not s.startswith("X"):
            continue
        f = s.split()
        if len(f) < 6:
            continue
        params = dict(t.split("=", 1) for t in f[6:] if "=" in t)
        devs.append((f[0], f[1:5], f[5], params))
    return devs


def check(devs) -> tuple[list[str], dict]:
    problems: list[str] = []
    tags = cell_tags()
    pad_nets = {"d_" + t for t in tags} | {"db_" + t for t in tags}
    rails = set(ANALOG_PORTS)
    allnets: set[str] = set()

    def num(tok):
        m = re.match(r"^([-+0-9.eE]+)([a-zA-Z]*)$", tok)
        if not m:
            return None
        v = float(m.group(1))
        return v * {"": 1, "u": 1, "m": 1e-3, "k": 1e3}.get(m.group(2), 1)

    mirror: dict[str, str] = {}     # md -> vdd (gate vbp)
    cascode: dict[str, str] = {}    # tail -> md (gate vcp)
    diode_m = diode_c = 0
    for name, nodes, sub, params in devs:
        d, g, s, b = nodes
        t = {d, s}
        allnets.update(nodes)
        w, l = params.get("w"), params.get("l")
        if w is None or l is None:
            problems.append(f"{name}: missing w/l")
            continue
        wv, lv = num(w), num(l)
        if wv is None or lv is None or abs(wv - W_UM) > 1e-6 or abs(lv - L_UM) > 1e-6:
            problems.append(f"{name}: {w}/{l} um, want {W_UM:g}/{L_UM:g}")
        if sub == PFET:
            if b != "vdd":
                problems.append(f"{name}: pfet bulk {b}, want vdd")
            if g == "vbp":
                if "vbp" in t:
                    diode_m += 1
                    if t != {"vdd", "vbp"}:
                        problems.append(f"{name}: replica mirror terminals {t}, "
                                        f"want vdd+vbp")
                else:
                    if "vdd" not in t or len(t) != 2:
                        problems.append(f"{name}: mirror terminals {t}, want "
                                        f"vdd + an internal node")
                        continue
                    md = (t - {"vdd"}).pop()
                    if md in rails or md in pad_nets:
                        problems.append(f"{name}: mirror internal {md} is a "
                                        f"rail/pad")
                    mirror[md] = name
            elif g == "vcp":
                if "vcp" in t:
                    diode_c += 1
                    if t != {"vbp", "vcp"}:
                        problems.append(f"{name}: replica cascode terminals "
                                        f"{t}, want vbp+vcp")
                else:
                    if len(t) != 2:
                        problems.append(f"{name}: cascode terminals {t}")
                        continue
                    for n in t:
                        if n in rails or n in pad_nets:
                            problems.append(f"{name}: cascode terminal {n} is a "
                                            f"rail/pad")
                    a, bb = sorted(t)
                    cascode[a] = bb
                    cascode[bb] = a
            else:
                problems.append(f"{name}: pfet gate {g}, want vbp/vcp")
        elif sub == NFET:
            if b not in ("VSUBS", "vss"):
                problems.append(f"{name}: nfet bulk {b}, want VSUBS/vss")
            if g not in pad_nets:
                problems.append(f"{name}: nfet gate {g} is not a pad")
            if len(t) != 2:
                problems.append(f"{name}: pair terminals {t}")
                continue
            drains = t & {"iout", "idump"}
            if len(drains) != 1:
                problems.append(f"{name}: pair drain set {t}, want one of "
                                f"iout/idump")
            if g in pad_nets and drains:
                tails = t - drains
                if len(tails) == 1:
                    tail = tails.pop()
                    if tail in rails or tail in pad_nets:
                        problems.append(f"{name}: tail {tail} is a rail/pad")
                    cascode.setdefault("tail:" + tail, name)
        else:
            problems.append(f"{name}: unexpected device {sub}")

    n_p = sum(1 for d in devs if d[2] == PFET)
    n_n = sum(1 for d in devs if d[2] == NFET)
    if len(devs) != 1022 or n_p != 512 or n_n != 510:
        problems.append(f"{len(devs)} devices ({n_p} pfet, {n_n} nfet), want "
                        f"1022 (512/510)")
    if diode_m != 1 or diode_c != 1:
        problems.append(f"{diode_m} replica mirrors, {diode_c} replica "
                        f"cascodes, want 1/1")

    gate = {}
    for name, nodes, sub, params in devs:
        if sub != NFET:
            continue
        d, g, s, b = nodes
        t = {d, s}
        dn = (t & {"iout", "idump"})
        if len(t) == 2 and len(dn) == 1 and g in pad_nets:
            gate[g] = ((t - dn).pop(), dn.pop())
    if len(gate) != 2 * N_CELLS:
        problems.append(f"{len(gate)} pad gates, want {2 * N_CELLS}")
    used_mirror = set()
    for tag in tags:
        a, bb = "d_" + tag, "db_" + tag
        if a not in gate or bb not in gate:
            problems.append(f"{tag}: a pad has no switch gate")
            continue
        ta, da = gate[a]
        tb, db_ = gate[bb]
        if da != "iout":
            problems.append(f"{a}: drain {da}, want iout")
        if db_ != "idump":
            problems.append(f"{bb}: drain {db_}, want idump")
        if ta != tb:
            problems.append(f"{tag}: the pair's tails differ ({ta} vs {tb})")
            continue
        md = cascode.get(ta)
        if md is None:
            problems.append(f"{tag}: tail {ta} is not a cascode terminal")
            continue
        if md not in mirror:
            problems.append(f"{tag}: cascode terminal {md} is not a mirror "
                            f"terminal")
            continue
        used_mirror.add(md)
    if len(used_mirror) != N_CELLS:
        problems.append(f"{len(used_mirror)} mirrors used by cells, want "
                        f"{N_CELLS}")
    if len(mirror) != N_CELLS:
        problems.append(f"{len(mirror)} cell mirrors, want {N_CELLS}")

    want_nets = (len(rails) + len(pad_nets) + 2 * N_CELLS
                 + (1 if "VSUBS" in allnets else 0))
    if len(allnets) != want_nets:
        problems.append(f"{len(allnets)} nets, want {want_nets} "
                        f"(6 rails + 510 pads + 2 internal/cell + VSUBS)")
    return problems, {"devices": len(devs), "pfet": n_p, "nfet": n_n,
                      "nets": len(allnets), "mirrors": len(mirror),
                      "cascodes": len(cascode) // 2}


def lvs(pdk: Path) -> dict:
    spice = MAGIC_DIR / "lvs.spice"
    magic(pdk, "extract_lvs.tcl",
          read_top() +
          "port makeall\n"
          "extract\n"
          "ext2spice hierarchy off\n"
          "ext2spice subcircuits off\n"
          f"ext2spice -o {spice}\n"
          f"puts LVS_DONE\n"
          "quit -noprompt\n")
    txt = spice.read_text()
    if "LVS_DONE" not in (MAGIC_DIR / "extract_lvs.log").read_text():
        die("magic LVS did not finish")
    devs = parse_flat(txt)
    problems, stats = check(devs)
    return {"ok": not problems, "problems": problems[:20], **stats,
            "spice": str(spice)}


def _tran_decks(pdk: Path):
    lib = pdk / "sky130A/libs.tech/ngspice/sky130.lib.spice"
    body = [ln for ln in (MAGIC_DIR / "pex.spice").read_text().splitlines()
            if not ln.strip().startswith((".subckt", ".ends"))]
    tags = cell_tags()
    head = ["* sky130 carry 127 -> 128", f'.lib "{lib}" tt'] + body
    head += ["Vdd vdd 0 3.3", "Vss vss 0 0", "Iref vcp 0 16u",
             "Vdump idump 0 0", "Rl iout 0 37.5", "Cl iout 0 2p",
             "Cvcp vcp 0 100p"]
    op = list(head)
    for j, t in enumerate(tags):
        on = (128 >> cell_bit(j)) & 1
        op += [f"Vd_{t} d_{t} 0 {3.3 if on else 0}",
               f"Vdb_{t} db_{t} 0 {0 if on else 3.3}"]
    op += [".op", ".control", "run", "print v(iout) v(vbp) v(vcp)",
           ".endc", ".end"]
    (BUILD / "tran_op.spice").write_text("\n".join(op) + "\n")
    tr = list(head)
    t0, edge, skew = 1e-9, 20e-12, 25e-12
    for j, t in enumerate(tags):
        k = cell_bit(j)
        g0 = 3.3 if (127 >> k) & 1 else 0.0
        g1 = 3.3 if (128 >> k) & 1 else 0.0
        tt = t0 + k * skew
        tr.append(f"Vd_{t} d_{t} 0 PWL(0 {g0} {tt} {g0} {tt + edge} {g1})")
        tr.append(f"Vdb_{t} db_{t} 0 PWL(0 {3.3 - g0} {tt} {3.3 - g0} "
                  f"{tt + edge} {3.3 - g1})")
    tr += [".tran 5p 40n", ".control", "run",
           f"wrdata {BUILD / 'tran.dat'} v(iout) v(vbp) v(vcp)",
           ".endc", ".end"]
    (BUILD / "tran.spice").write_text("\n".join(tr) + "\n")


def tran(pdk: Path) -> dict:
    """Carry 127 -> 128 on the extracted netlist with its capacitance."""
    pex = MAGIC_DIR / "pex.spice"
    if not pex.is_file():
        die("no build/magic/pex.spice; run --stage pex first")
    if pex.stat().st_mtime < GDS.stat().st_mtime:
        die("pex.spice is older than the GDS; rerun --stage pex")
    _tran_decks(pdk)
    env = dict(os.environ)
    env["PDK_ROOT"] = str(pdk)
    env["PDK"] = "sky130A"
    p = run(["ngspice", "-b", BUILD / "tran_op.spice"], cwd=BUILD, env=env,
            timeout=3600)
    (BUILD / "tran_op.log").write_text(p.stdout + p.stderr)
    txt = p.stdout + p.stderr
    def grab(name):
        m = re.search(rf"v\({name}\)\s*=\s*([-+0-9.eE]+)", txt, re.I)
        if not m:
            die(f"tran op produced no v({name})")
        return float(m.group(1))
    iout0, vbp0, vcp0 = grab("iout"), grab("vbp"), grab("vcp")
    p = run(["ngspice", "-b", BUILD / "tran.spice"], cwd=BUILD, env=env,
            timeout=7200)
    (BUILD / "tran.log").write_text(p.stdout + p.stderr)
    rows = []
    for ln in (BUILD / "tran.dat").read_text().splitlines():
        f = ln.split()
        if len(f) >= 6:
            try:
                rows.append([float(v) for v in f[:6]])
            except ValueError:
                pass
    if not rows:
        die("tran produced no samples")
    # wrdata writes a scale column before each vector: t, iout, t, vbp,
    # t, vcp.
    t, iout, vbp, vcp = (rows[-1][0], rows[-1][1], rows[-1][3],
                         rows[-1][5])
    lsb_v = 16e-6 * 37.5
    err_lsb = abs(iout - iout0) / lsb_v
    ok = (abs(t - 40e-9) < 1e-9 and err_lsb <= 0.5
          and abs(vbp - vbp0) <= 2e-3 and abs(vcp - vcp0) <= 2e-3)
    return {"ok": ok, "t_ns": round(t * 1e9, 2),
            "iout_mV": round(iout * 1e3, 4),
            "iout_dc_mV": round(iout0 * 1e3, 4),
            "settle_lsb": round(err_lsb, 3),
            "vbp_mV_drift": round((vbp - vbp0) * 1e3, 3),
            "vcp_mV_drift": round((vcp - vcp0) * 1e3, 3),
            "log": str(BUILD / "tran.log")}


def pins() -> dict:
    out = BUILD / "pinplan.json"
    p = run([KLAYOUT_BUILD, "-b", "-r", ROOT / "pinplan.py",
             "-rd", f"gds={GDS}", "-rd", f"out={out}"])
    if p.returncode or not out.is_file():
        print(p.stdout + p.stderr, file=sys.stderr)
        die("pinplan extraction failed")
    plan = json.loads(out.read_text())
    y0, y1 = PIN_Y_UM
    pads = [s for s in plan["shapes"]
            if s["layer"] == "m2"
            and abs(s["y1"] - y0) < 1e-3 and abs(s["y2"] - y1) < 1e-3]
    pads.sort(key=lambda s: (s["x1"] + s["x2"]) / 2)
    problems = []
    if len(pads) != 2 * N_CELLS:
        problems.append(f"{len(pads)} pads at y {PIN_Y_UM}, want {2 * N_CELLS}")
    for j in range(min(len(pads), 2 * N_CELLS)):
        want_x = (j // 2) * 2 * PIN_PITCH_UM + PIN_X0_UM + (j % 2) * PIN_PITCH_UM
        cx = (pads[j]["x1"] + pads[j]["x2"]) / 2
        w = pads[j]["x2"] - pads[j]["x1"]
        if abs(cx - want_x) > 1e-3 or abs(w - PIN_W_UM) > 1e-3:
            problems.append(f"pad {j}: x {pads[j]['x1']:.3f}..{pads[j]['x2']:.3f}"
                            f", want centre {want_x:.3f} width {PIN_W_UM}")
            if len(problems) > 8:
                break
    labels = {l["net"] for l in plan["labels"]}
    want_labels = ({"d_" + t for t in cell_tags()}
                   | {"db_" + t for t in cell_tags()})
    missing = want_labels - labels
    if missing:
        problems.append(f"{len(missing)} pad labels missing, e.g. "
                        f"{sorted(missing)[:3]}")
    for p_ in ANALOG_PORTS:
        if p_ not in labels:
            problems.append(f"rail label {p_} missing")
    return {"ok": not problems, "pads": len(pads),
            "labels": len(labels), "problems": problems[:10]}


def pex(pdk: Path) -> dict:
    spice = MAGIC_DIR / "pex.spice"
    magic(pdk, "extract_pex.tcl",
          read_top() +
          "extract\n"
          "ext2spice hierarchy on\n"
          "ext2spice cthresh 0\n"
          "ext2spice rthresh 0\n"
          f"ext2spice -o {spice}\n"
          "puts PEX_DONE\n"
          "quit -noprompt\n", timeout=7200)
    txt = spice.read_text()
    x = [ln for ln in txt.splitlines() if ln.strip().startswith("X")]
    caps = [ln for ln in txt.splitlines() if ln.strip().startswith("C")]
    floating = [ln for ln in txt.splitlines() if "**FLOATING" in ln]
    total = 0.0
    for ln in caps:
        f = ln.split()
        try:
            v = f[3]
            m = re.match(r"^([-+0-9.eE]+)([fpnumk]?)", v)
            total += float(m.group(1)) * {"f": 1e-15, "p": 1e-12,
                                          "n": 1e-9, "u": 1e-6,
                                          "m": 1e-3, "": 1}[m.group(2)]
        except Exception:
            pass
    ok = len(x) == 1022 and not floating
    return {"ok": ok, "instances": len(x), "caps": len(caps),
            "cap_ff": round(total * 1e15, 1), "floating": len(floating),
            "spice": str(spice)}


def _tags() -> list[str]:
    return cell_tags()


def _mm_deck(pdk: Path, seed: int, mismatch: bool, dat: Path) -> Path:
    lib = pdk / "sky130A/libs.tech/ngspice/sky130.lib.spice"
    src = (MAGIC_DIR / "lvs.spice").read_text().splitlines()
    devs = [ln for ln in src if ln.startswith("X")]
    out = ["* sky130 one-hot mismatch sweep",
           f'.lib "{lib}" tt',
           f".param mc_mm_switch={1 if mismatch else 0}", ""] + devs
    out += ["Vdd vdd 0 3.3", "Vss vss 0 0", "Iref vcp 0 16u",
            "Vdump idump 0 0", "Vsel sel 0 0"]
    for j, t in enumerate(_tags()):
        on = f"(abs(v(sel)-{j})<0.5)"
        out += [f"Bd_{t} d_{t} 0 V = 3.3*{on}",
                f"Bdb_{t} db_{t} 0 V = 3.3*(1-{on})"]
    out += ["Vmi iout 0 0", ".control", f"setseed {seed}",
            "dc Vsel 0 254 1", f"wrdata {dat} i(Vmi)", ".endc", ".end"]
    deck = BUILD / (f"mm_seed{seed}.spice" if mismatch else "mm_base.spice")
    deck.write_text("\n".join(out) + "\n")
    return deck


def _mm_cells(dat: Path) -> list[float]:
    rows = []
    for ln in dat.read_text().splitlines():
        f = ln.split()
        if len(f) >= 2:
            try:
                rows.append(abs(float(f[1])))
            except ValueError:
                pass
    if len(rows) < 255:
        die(f"{dat.name}: {len(rows)} points, want 255")
    return rows[:255]


def _transfer(cells: list[float], decode: str = "binary") -> list[float]:
    out = []
    for code in range(256):
        if decode == "thermo":
            out.append(sum(cells[:code]))
        else:
            out.append(sum(cells[j] for j in range(255)
                           if (code >> cell_bit(j)) & 1))
    return out


def _dnl_inl(vals: list[float]) -> tuple[list[float], list[float]]:
    i0, fs = vals[0], vals[-1] - vals[0]
    if fs <= 0:
        die("mismatch transfer full scale is not positive")
    lsb = fs / 255.0
    dnl = [(vals[c + 1] - vals[c]) / lsb - 1.0 for c in range(255)]
    inl = [(vals[c] - i0 - c * lsb) / lsb for c in range(256)]
    return dnl, inl


def mm(pdk: Path, samples: int = 16, seed0: int = 0) -> dict:
    """Static mismatch Monte Carlo on the PDK's own statistical model."""
    lvs = MAGIC_DIR / "lvs.spice"
    if not lvs.is_file():
        die("no build/magic/lvs.spice; run --stage lvs first")
    if lvs.stat().st_mtime < GDS.stat().st_mtime:
        die("lvs.spice is older than the GDS; rerun --stage lvs")
    env = dict(os.environ)
    env["PDK_ROOT"] = str(pdk)
    env["PDK"] = "sky130A"

    base = _mm_deck(pdk, 0, False, BUILD / "mm_base.dat")
    p = run(["ngspice", "-b", base], cwd=BUILD, env=env, timeout=3600)
    (BUILD / "mm_base.log").write_text(p.stdout + p.stderr)
    cells0 = _mm_cells(BUILD / "mm_base.dat")
    want = 16e-6
    base_err = max(abs(c / want - 1) for c in cells0)
    if base_err > 0.02:
        die(f"zero-mismatch cells deviate {base_err * 100:.2f}% from 16 uA")

    spreads, dnl_max, inl_max, bad = [], [], [], []
    dnl_b, inl_b, bad_b = [], [], []
    for s in range(samples):
        seed = seed0 + s
        dat = BUILD / f"mm_seed{seed}.dat"
        deck = _mm_deck(pdk, seed, True, dat)
        p = run(["ngspice", "-b", deck], cwd=BUILD, env=env, timeout=3600)
        (BUILD / f"mm_seed{seed}.log").write_text(p.stdout + p.stderr)
        cells = _mm_cells(dat)
        vals = _transfer(cells, "thermo")
        dnl, inl = _dnl_inl(vals)
        spreads.append((max(cells) - min(cells)) / (sum(cells) / len(cells)))
        dnl_max.append(max(abs(v) for v in dnl))
        inl_max.append(max(abs(v) for v in inl))
        if any(vals[c + 1] < vals[c] for c in range(255)):
            bad.append(seed)
        vb = _transfer(cells, "binary")
        db, ib = _dnl_inl(vb)
        dnl_b.append(max(abs(v) for v in db))
        inl_b.append(max(abs(v) for v in ib))
        if any(vb[c + 1] < vb[c] for c in range(255)):
            bad_b.append(seed)
    mean = sum(cells0) / len(cells0)
    import statistics
    sigma = statistics.pstdev(_mm_cells(BUILD / "mm_seed0.dat")) / mean
    ok = (not bad and max(dnl_max) <= 0.5 and max(inl_max) <= 1.0
          and 0.001 < sigma < 0.05)
    return {"ok": ok, "samples": samples,
            "decode": "thermometer (array physical linearity)",
            "zero_mismatch_cell_error_pct": round(base_err * 100, 3),
            "cell_sigma_pct": round(sigma * 100, 3),
            "spread_pct_max": round(max(spreads) * 100, 3),
            "dnl_max_lsb": round(max(dnl_max), 4),
            "inl_max_lsb": round(max(inl_max), 4),
            "nonmonotonic_seeds": bad,
            "binary_dnl_max_lsb": round(max(dnl_b), 4),
            "binary_inl_max_lsb": round(max(inl_b), 4),
            "binary_nonmonotonic_seeds": bad_b,
            "log": str(BUILD / "mm_seed0.log")}


def dc(pdk: Path) -> dict:
    """Extracted DC: 255 cells to iout, 16 uA at vcp; gate the full scale."""
    pex = MAGIC_DIR / "pex.spice"
    if not pex.is_file():
        die("no build/magic/pex.spice; run --stage pex first")
    if pex.stat().st_mtime < GDS.stat().st_mtime:
        die("pex.spice is older than the GDS; rerun --stage pex")
    lib = pdk / "sky130A/libs.tech/ngspice/sky130.lib.spice"
    if not lib.is_file():
        die(f"no ngspice library at {lib}")
    body = [ln for ln in pex.read_text().splitlines()
            if not ln.strip().startswith((".subckt", ".ends"))]
    out = ["* sky130 extracted array DC: all 255 cells to iout",
           f'.lib "{lib}" tt', ""] + body
    out += ["", "Vdd vdd 0 3.3", "Vss vss 0 0", "Iref vcp 0 16u",
            "Viout iout 0 0", "Vdump idump 0 0"]
    for tag in cell_tags():
        out += [f"Vd_{tag} d_{tag} 0 3.3", f"Vdb_{tag} db_{tag} 0 0"]
    out += [".op", ".control", "run", "print i(Viout)", "print v(vbp) v(vcp)",
            ".endc", ".end"]
    deck = BUILD / "dc_transfer.spice"
    deck.write_text("\n".join(out) + "\n")
    env = dict(os.environ)
    env["PDK_ROOT"] = str(pdk)
    env["PDK"] = "sky130A"
    p = run(["ngspice", "-b", deck], cwd=BUILD, env=env, timeout=3600)
    (BUILD / "dc_transfer.log").write_text(p.stdout + p.stderr)
    m = re.search(r"i\(viout\)\s*=\s*([-+0-9.eE]+)", p.stdout + p.stderr, re.I)
    vb = re.search(r"v\(vbp\)\s*=\s*([-+0-9.eE]+)", p.stdout + p.stderr, re.I)
    vc = re.search(r"v\(vcp\)\s*=\s*([-+0-9.eE]+)", p.stdout + p.stderr, re.I)
    if not (m and vb and vc):
        die("ngspice produced no iout/vbp/vcp (see build/dc_transfer.log)")
    iout = abs(float(m.group(1)))
    vbp, vcp = float(vb.group(1)), float(vc.group(1))
    want = N_CELLS * 16e-6
    checks = {
        "iout_full_scale_mA": round(iout * 1e3, 4),
        "iout_error_pct": round((iout / want - 1) * 100, 3),
        "vbp_V": round(vbp, 4), "vcp_V": round(vcp, 4),
    }
    ok = (abs(iout / want - 1) < 0.02 and 1.8 < vbp < 2.5
          and 0.5 < vcp < 1.2)
    return {"ok": ok, **checks, "want_mA": round(want * 1e3, 3),
            "netlist": str(deck), "log": str(BUILD / "dc_transfer.log")}


def selftest() -> int:
    """Mutate the extracted netlist and prove the contract rejects it."""
    spice = MAGIC_DIR / "lvs.spice"
    if not spice.is_file():
        die("no build/magic/lvs.spice; run --stage lvs first")
    devs = parse_flat(spice.read_text())
    problems, _ = check(devs)
    if problems:
        print("baseline fails:", problems[:3])
        return 1

    def mutated(fn):
        d = [(n, list(nodes), s, dict(p)) for n, nodes, s, p in devs]
        fn(d)
        return check(d)[0]

    tests = []
    def swap_pad_gate(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == NFET and nodes[1].startswith("d_"):
                nodes[1] = "d_b0_0"       # duplicate gate
                break
    tests.append(("duplicate pad gate", swap_pad_gate))
    def open_tail(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == NFET:
                nodes[2] = "floating_tail"
                d[i] = (n, nodes, s, p)
                break
    tests.append(("open tail", open_tail))
    def pfet_bulk(d):
        for i, (n, nodes, s, p) in enumerate(d):
            if s == PFET:
                nodes[3] = "vss"
                break
    tests.append(("pfet bulk vss", pfet_bulk))
    bad = []
    for name, fn in tests:
        if not mutated(fn):
            bad.append(name)
    print(f"selftest: {len(tests) - len(bad)}/{len(tests)} mutations rejected")
    if bad:
        print("NOT rejected:", bad)
        return 1
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all",
                    choices=["all", "build", "drc", "lvs", "pins", "pex", "dc", "mm", "tran"])
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--samples", type=int, default=16)
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    pdk = find_pdk()
    report = {}
    stages = (["build", "drc", "lvs", "pins", "pex", "dc", "mm", "tran"] if a.stage == "all"
              else [a.stage])
    rc = 0
    for st in stages:
        fn = {"build": build, "drc": drc, "lvs": lvs,
              "pins": pins, "pex": pex, "dc": dc, "mm": mm,
              "tran": tran}[st]
        try:
            if st == "build":
                res = build()
            elif st == "pins":
                res = pins()
            elif st == "mm":
                res = mm(pdk, a.samples)
            else:
                res = fn(pdk)
        except SystemExit:
            raise
        report[st] = res
        print(json.dumps({st: res}, indent=2)[:1600])
        if not res.get("ok", True):
            rc = 1
    (BUILD / "signoff.json").write_text(json.dumps(report, indent=2))
    return rc


if __name__ == "__main__":
    sys.exit(main())
