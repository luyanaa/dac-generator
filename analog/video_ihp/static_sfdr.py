#!/usr/bin/env python3
"""Static SFDR / PPA for the IHP 1.2 V video DAC.

    python3 static_sfdr.py

The row settles in ~2.3 ns while the 25 MS/s update period is 40 ns, so the
spectrum is dominated by the static transfer.  The 16-seed PSP103 mismatch
one-hot data (`build/mm_seed*.dat`, generated by `signoff.py --stage mm`) is
superposed into the 256-code binary transfer; a 256-sample coherent sine
(7 cycles) is evaluated through that transfer and the FFT gives SFDR / SNDR /
ENOB.  The zero-mismatch base data is the reference.  PPA uses the extracted
DC current, the digital macro metrics, and the assembled area.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

import signoff as so

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"
RL = 37.5
VDD = so.VDD
LSB = so.IREF_UA * 1e-6 * RL
SAMPLES = 256
CYCLES = 7
NSEEDS = 16


def fft_metrics(y: np.ndarray, cycles: int = CYCLES) -> dict:
    n = len(y)
    y = y - y.mean()
    mag = np.abs(np.fft.rfft(y)) / n * 2
    mag[0] = 0.0
    k = cycles
    fund = mag[k]
    mask = np.ones_like(mag, dtype=bool)
    mask[0] = False
    mask[k] = False
    for d in (-1, 1):
        if 0 <= k + d < len(mag):
            mask[k + d] = False
    spur = float(mag[mask].max()) if mask.any() else 0.0
    nd = float((mag[mask] ** 2).sum())
    sfdr = 20 * math.log10(fund / spur) if spur > 0 else float("inf")
    sndr = 10 * math.log10(fund ** 2 / nd) if nd > 0 else float("inf")
    return {"sfdr_db": sfdr, "sndr_db": sndr,
            "enob": (sndr - 1.76) / 6.02,
            "fundamental_mv": float(fund * 1e3),
            "spur_mv": spur * 1e3}


def sine_codes() -> np.ndarray:
    return np.array([
        max(0, min(255, int(round(127.5 + 127.5 * math.sin(
            2 * math.pi * CYCLES * n / SAMPLES)))))
        for n in range(SAMPLES)
    ], dtype=int)


def metrics_for(cells: list[float]) -> tuple[dict, list[float]]:
    vals = so._transfer(cells)
    codes = sine_codes()
    y = np.array([vals[c] for c in codes]) * RL
    return fft_metrics(y), vals


def main() -> int:
    base = so._mm_cells(BUILD / "mm_base.dat")
    base_m, base_vals = metrics_for(base)
    seeds = []
    worst = None
    for s in range(NSEEDS):
        p = BUILD / f"mm_seed{s}.dat"
        if not p.is_file():
            raise SystemExit(f"missing {p}; run signoff.py --stage mm first")
        cells = so._mm_cells(p)
        m, vals = metrics_for(cells)
        m["seed"] = s
        seeds.append(m)
        if worst is None or m["sfdr_db"] < worst["sfdr_db"]:
            worst = m
    sfdr = [s["sfdr_db"] for s in seeds]
    sndr = [s["sndr_db"] for s in seeds]

    # PPA: full-scale DC current with all 255 cells on.
    i_fs = base_vals[-1]  # code 255
    p_analog_fs = i_fs * VDD
    # Average sine current through the measured zero-mismatch transfer.
    codes = sine_codes()
    i_avg = float(np.mean([base_vals[c] for c in codes]))
    p_analog_avg = i_avg * VDD
    p_digital = 0.0003865057951770723  # ihp_ant final metrics
    analog_area = 1918.5 * 26.6
    digital_die_area = 1912.5 * 100.0
    assembled_area = 1918.5 * (12.0 - (-109.8))

    out = {
        "pdk": "ihp-sg13g2",
        "vdd_V": VDD,
        "iref_uA": so.IREF_UA,
        "cvcp_pF": so.VCP_CAP_PF,
        "cvbp_pF": 100.0,
        "samples": SAMPLES,
        "cycles": CYCLES,
        "update_rate_msps": 25.0,
        "lsb_mv": LSB * 1e3,
        "static_sfdr": {
            "zero_mismatch": base_m,
            "worst_seed": worst,
            "mean_sfdr_db": float(np.mean(sfdr)),
            "min_sfdr_db": float(np.min(sfdr)),
            "max_sfdr_db": float(np.max(sfdr)),
            "mean_sndr_db": float(np.mean(sndr)),
            "min_sndr_db": float(np.min(sndr)),
            "mean_enob": float(np.mean([s["enob"] for s in seeds])),
            "min_enob": float(np.min([s["enob"] for s in seeds])),
            "seeds": seeds,
        },
        "ppa": {
            "analog_area_um2": analog_area,
            "digital_die_area_um2": digital_die_area,
            "assembled_bbox_um2": assembled_area,
            "analog_i_fs_mA": i_fs * 1e3,
            "analog_power_fs_mW": p_analog_fs * 1e3,
            "analog_power_sine_avg_mW": p_analog_avg * 1e3,
            "digital_power_mW": p_digital * 1e3,
            "total_power_fs_mW": (p_analog_fs + p_digital) * 1e3,
            "total_power_sine_avg_mW": (p_analog_avg + p_digital) * 1e3,
            "energy_pj_per_sample": (
                (p_analog_fs + p_digital) / 25e6 * 1e12),
        },
    }
    (BUILD / "static_sfdr.json").write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
