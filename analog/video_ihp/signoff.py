#!/usr/bin/env python3
"""Signoff for the ihp-sg13g2 255-cell dump-tail video array.

    ./signoff.py                 # build + drc + lvs + pins
    ./signoff.py --stage drc
    ./signoff.py --selftest      # prove the LVS gates reject mutations

The array is generated by `gen_gds.py` from the PDK's `SG13_dev` PCells:
1022 devices (512 pmos, 510 nmos), 255 cells on a 7.5 um pitch, the 510 met2
pads on the 3.75 um grid, and the diode-connected replica.

Gates:
  build  gen_gds.py under KLayout with the sg13g2 technology; the generator's
         own same-layer short check must pass.
  drc    the PDK's `tech/drc/ihp-sg13g2.drc` (KLayout, no `run_drc.py` - that
         script needs the `klayout` pip module this environment lacks);
         0 items on the full array.
  lvs    the PDK's `tech/lvs/run_lvs.py --net_only` extraction (the runner
         needs KLayout >= 0.30.7 for its version gate and the `klayout`
         python module; both are wired up here), then a pad-pair walk
         independent of the extractor's node names: pad -> nmos -> shared
         tail -> cascode -> mirror -> vdd.  pmos bulk vdd, nmos bulk vss.
  pins   the 510 met2 pads measured on the drawn GDS on the 3.75 um grid,
         with their d_/db_ labels (10/25).

Not claimed: PEX and the benches.  The PDK has no KLayout PEX deck; a magic
tech exists but its device extractor has not been validated for these PCell
devices, so the leaf stops at DRC/LVS/pins.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
GDS = BUILD / "video_ihp.gds"
TOP = "dac_video_ihp"
KLAYOUT = "/usr/bin/klayout"
KLAYOUT_DECK = "/nix/store/1whjbzm6gw6l4h0sjxdv92lyw7lq1ar8-klayout-0.30.12/bin/klayout"
KLAYOUT_PYMOD = "/usr/lib/klayout/pymod"
KLAYOUT_LIBS = "/usr/lib/klayout"

PITCH = 7.5
PAD_Y = (-10.00, -9.60)
PAD_W = 0.60
PIN_A, PIN_B = 2.25, 6.00
N_CELLS = 255
RAILS = {"vdd", "vss", "vbp", "vcp", "iout", "idump"}


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def run(cmd, cwd=None, env=None, timeout=3600):
    return subprocess.run([str(c) for c in cmd], cwd=cwd, env=env,
                          capture_output=True, text=True, timeout=timeout)


def find_pdk() -> Path:
    cand = Path("/grid/dac-generator/pdks/ihp-sg13g2")
    if (cand / "libs.tech/klayout").is_dir():
        return cand
    base = Path.home() / ".ciel/ciel/ihp-sg13/versions"
    hits = sorted(p / "ihp-sg13g2" for p in base.iterdir()
                  if (p / "ihp-sg13g2/libs.tech/klayout").is_dir())
    if not hits:
        die(f"no ihp-sg13g2 PDK under {cand} or {base}")
    return hits[-1]


def cell_tags() -> list[str]:
    tags = []
    for j in range(N_CELLS):
        k = 0
        while j >= 2 ** (k + 1) - 1:
            k += 1
        tags.append(f"b{k}_{j - (2 ** k - 1)}")
    return tags


def build(pdk: Path) -> dict:
    env = dict(os.environ)
    env["KLAYOUT_PATH"] = str(pdk / "libs.tech/klayout")
    p = run([KLAYOUT, "-b", "-r", ROOT / "gen_gds.py",
             "-rd", f"out={GDS}"], cwd=ROOT, env=env, timeout=3600)
    (BUILD / "gen.log").write_text(p.stdout + p.stderr)
    if p.returncode:
        die("array generation failed or reported a short (build/gen.log)")
    return {"ok": True,
            "note": (p.stdout + p.stderr).strip().splitlines()[-1],
            "log": str(BUILD / "gen.log")}


def drc(pdk: Path) -> dict:
    deck = pdk / "libs.tech/klayout/tech/drc/ihp-sg13g2.drc"
    rdb = BUILD / "drc.lyrdb"
    if rdb.exists():
        rdb.unlink()
    p = run([KLAYOUT_DECK, "-b", "-r", deck,
             "-rd", f"input={GDS}", "-rd", f"report={rdb}",
             "-rd", f"topcell={TOP}"], timeout=7200)
    (BUILD / "drc.log").write_text(p.stdout + p.stderr)
    if p.returncode or not rdb.is_file():
        die("ihp DRC did not produce a report (build/drc.log)")
    import xml.etree.ElementTree as ET
    root = ET.parse(rdb).getroot()
    items = root.findall("./items/item")
    cats = Counter((it.findtext("category") or "").strip("'") for it in items)
    return {"ok": not items, "items": len(items),
            "categories": dict(cats.most_common()), "log": str(BUILD / "drc.log")}


def _lvs_env(pdk: Path) -> dict:
    """The PDK runner checks `klayout -b -v` and imports the klayout module."""
    b = BUILD / "bin"
    b.mkdir(parents=True, exist_ok=True)
    wrapper = b / "klayout"
    wrapper.write_text("#!/bin/sh\nexec env -u LD_LIBRARY_PATH "
                       f"{KLAYOUT_DECK} \"$@\"\n")
    wrapper.chmod(0o755)
    env = dict(os.environ)
    env["PATH"] = f"{b}:" + env.get("PATH", "")
    env["PYTHONPATH"] = KLAYOUT_PYMOD + ":" + env.get("PYTHONPATH", "")
    env["LD_LIBRARY_PATH"] = KLAYOUT_LIBS + ":" + env.get("LD_LIBRARY_PATH", "")
    return env


def parse_lvs(txt: str):
    body = []
    for ln in txt.splitlines():
        if ln.startswith("+"):
            body[-1] += " " + ln[1:].strip()
        else:
            body.append(ln)
    sub = next((ln for ln in body if ln.startswith(".SUBCKT")), None)
    if not sub:
        return [], [], []
    ports = sub.split()[2:]
    devs = []
    for ln in body:
        f = ln.split()
        if not f or not f[0].startswith("M"):
            continue
        # M<name> d g s b model k=v ...
        if len(f) < 6:
            continue
        params = dict(t.split("=", 1) for t in f[6:] if "=" in t)
        devs.append((f[0], f[1:5], f[5], params))
    nets = set()
    for _, nodes, _, _ in devs:
        nets.update(nodes)
    return ports, devs, nets


def check(ports, devs) -> tuple[list[str], dict]:
    problems: list[str] = []
    tags = cell_tags()
    pad_nets = {"d_" + t for t in tags} | {"db_" + t for t in tags}
    if len(ports) != len(pad_nets) + len(RAILS):
        problems.append(f"{len(ports)} top ports, want "
                        f"{len(pad_nets) + len(RAILS)}")
    missing = (pad_nets | RAILS) - set(ports)
    if missing:
        problems.append(f"missing ports: {sorted(missing)[:4]}")
    mirrors: dict[str, str] = {}
    cascodes: dict[str, str] = {}
    diode_m = diode_c = 0
    n_p = n_n = 0
    for name, nodes, model, params in devs:
        d, g, s, b = nodes
        t = {d, s}
        if model == "sg13_lv_pmos":
            n_p += 1
            if b != "vdd":
                problems.append(f"{name}: pmos bulk {b}, want vdd")
            w, l = params.get("W"), params.get("L")
            if g == "vbp":
                if "vbp" in t:
                    diode_m += 1
                    if t != {"vdd", "vbp"}:
                        problems.append(f"{name}: replica mirror {t}")
                else:
                    if "vdd" not in t or len(t) != 2:
                        problems.append(f"{name}: mirror terminals {t}")
                        continue
                    md = (t - {"vdd"}).pop()
                    if md in RAILS or md in pad_nets:
                        problems.append(f"{name}: mirror node {md} is a port")
                    mirrors[md] = name
                if w != "8u":
                    problems.append(f"{name}: mirror W {w}, want 8u")
                if l not in ("1u", "1.0u"):
                    problems.append(f"{name}: mirror L {l}, want 1u")
            elif g == "vcp":
                if "vcp" in t:
                    diode_c += 1
                    if t != {"vbp", "vcp"}:
                        problems.append(f"{name}: replica cascode {t}")
                else:
                    if len(t) != 2:
                        problems.append(f"{name}: cascode terminals {t}")
                        continue
                    for nd in t:
                        if nd in RAILS or nd in pad_nets:
                            problems.append(f"{name}: cascode node {nd} is a "
                                            f"port")
                    a, bb = sorted(t)
                    cascodes[a] = bb
                    cascodes[bb] = a
                if w != "8u" or l not in ("0.5u", "0.50u"):
                    problems.append(f"{name}: cascode {w}/{l}, want 8/0.5")
            else:
                problems.append(f"{name}: pmos gate {g}, want vbp/vcp")
        elif model == "sg13_lv_nmos":
            n_n += 1
            if b != "vss":
                problems.append(f"{name}: nmos bulk {b}, want vss")
            if g not in pad_nets:
                problems.append(f"{name}: nmos gate {g} is not a pad")
            if params.get("W") != "4u" or params.get("L") not in ("0.28u", "0.280u"):
                problems.append(f"{name}: pair {params.get('W')}/"
                                f"{params.get('L')}, want 4/0.28")
            if len(t) != 2:
                problems.append(f"{name}: pair terminals {t}")
                continue
            dn = t & {"iout", "idump"}
            if len(dn) != 1:
                problems.append(f"{name}: pair drain set {t}")
            elif g in pad_nets:
                tail = (t - dn).pop()
                if tail in RAILS or tail in pad_nets:
                    problems.append(f"{name}: tail {tail} is a port")
                cascodes.setdefault("tail:" + tail, name)
        else:
            problems.append(f"{name}: unexpected model {model}")

    if len(devs) != 1022 or n_p != 512 or n_n != 510:
        problems.append(f"{len(devs)} devices ({n_p} pmos, {n_n} nmos), "
                        f"want 1022 (512/510)")
    if diode_m != 1 or diode_c != 1:
        problems.append(f"{diode_m}/{diode_c} replica devices, want 1/1")

    gate = {}
    for name, nodes, model, params in devs:
        if model != "sg13_lv_nmos":
            continue
        d, g, s, b = nodes
        t = {d, s}
        dn = t & {"iout", "idump"}
        if len(t) == 2 and len(dn) == 1 and g in pad_nets:
            gate[g] = ((t - dn).pop(), dn.pop())
    if len(gate) != 2 * N_CELLS:
        problems.append(f"{len(gate)} pad gates, want {2 * N_CELLS}")
    used = set()
    for tag in tags:
        a, bb = "d_" + tag, "db_" + tag
        if a not in gate or bb not in gate:
            problems.append(f"{tag}: a pad has no switch gate")
            continue
        ta, da = gate[a]
        tb, db_ = gate[bb]
        if da != "iout":
            problems.append(f"{a}: drain {da}, want iout")
        if db_ != "idump":
            problems.append(f"{bb}: drain {db_}, want idump")
        if ta != tb:
            problems.append(f"{tag}: pair tails differ")
            continue
        md = cascodes.get(ta)
        if md is None:
            problems.append(f"{tag}: tail {ta} is not a cascode terminal")
            continue
        if md not in mirrors:
            problems.append(f"{tag}: cascode node {md} is not a mirror node")
            continue
        used.add(md)
    if len(used) != N_CELLS:
        problems.append(f"{len(used)} mirrors used, want {N_CELLS}")
    if len(mirrors) != N_CELLS:
        problems.append(f"{len(mirrors)} cell mirrors, want {N_CELLS}")
    return problems, {"devices": len(devs), "pmos": n_p, "nmos": n_n,
                      "ports": len(ports), "mirrors": len(mirrors),
                      "cascodes": len(cascodes) // 2}


def lvs(pdk: Path) -> dict:
    run_dir = BUILD / "lvs_run"
    if run_dir.exists():
        shutil.rmtree(run_dir)
    runner = pdk / "libs.tech/klayout/tech/lvs/run_lvs.py"
    if not runner.is_file():
        die(f"no LVS runner at {runner}")
    env = _lvs_env(pdk)
    p = run(["/usr/bin/python3", runner, f"--layout={GDS}",
             f"--topcell={TOP}", f"--run_dir={run_dir}", "--net_only",
             "--disable_tap_extraction"], cwd=ROOT, env=env, timeout=7200)
    (BUILD / "lvs.log").write_text(p.stdout + p.stderr)
    cir = run_dir / f"{GDS.stem}_extracted.cir"
    if p.returncode or not cir.is_file():
        die("ihp LVS extraction failed (build/lvs.log)")
    ports, devs, nets = parse_lvs(cir.read_text())
    problems, stats = check(ports, devs)
    return {"ok": not problems, "problems": problems[:20], **stats,
            "netlist": str(cir)}


def pins() -> dict:
    out = BUILD / "pinplan.json"
    p = run([KLAYOUT, "-b", "-r", ROOT / "pinplan.py",
             "-rd", f"gds={GDS}", "-rd", f"out={out}"])
    if p.returncode or not out.is_file():
        print(p.stdout + p.stderr, file=sys.stderr)
        die("pinplan extraction failed")
    plan = json.loads(out.read_text())
    y0, y1 = PAD_Y
    pads = [s for s in plan["shapes"] if s["layer"] == "m2"
            and abs(s["y1"] - y0) < 1e-3 and abs(s["y2"] - y1) < 1e-3]
    pads.sort(key=lambda s: (s["x1"] + s["x2"]) / 2)
    problems = []
    if len(pads) != 2 * N_CELLS:
        problems.append(f"{len(pads)} pads at y {PAD_Y}, want {2 * N_CELLS}")
    for j in range(min(len(pads), 2 * N_CELLS)):
        want = (j // 2) * PITCH + PIN_A + (j % 2) * (PIN_B - PIN_A)
        cx = (pads[j]["x1"] + pads[j]["x2"]) / 2
        w = pads[j]["x2"] - pads[j]["x1"]
        if abs(cx - want) > 1e-3 or abs(w - PAD_W) > 1e-3:
            problems.append(f"pad {j}: x {pads[j]['x1']:.3f}.."
                            f"{pads[j]['x2']:.3f}, want centre {want:.3f}")
            if len(problems) > 8:
                break
    labels = {l["net"] for l in plan["labels"]}
    want_l = {"d_" + t for t in cell_tags()} | {"db_" + t for t in cell_tags()}
    missing = want_l - labels
    if missing:
        problems.append(f"{len(missing)} pad labels missing, e.g. "
                        f"{sorted(missing)[:3]}")
    for r in RAILS:
        if r not in labels:
            problems.append(f"rail label {r} missing")
    return {"ok": not problems, "pads": len(pads), "labels": len(labels),
            "problems": problems[:10]}


def selftest() -> int:
    cir = BUILD / "lvs_run" / f"{GDS.stem}_extracted.cir"
    if not cir.is_file():
        die("no extracted netlist; run --stage lvs first")
    ports, devs, _ = parse_lvs(cir.read_text())
    problems, _ = check(ports, devs)
    if problems:
        print("baseline fails:", problems[:3])
        return 1

    def mutated(fn):
        d = [(n, list(nodes), m, dict(p)) for n, nodes, m, p in devs]
        fn(d)
        return check(ports, d)[0]

    tests = []
    def dup_gate(d):
        for i, (n, nodes, m, p) in enumerate(d):
            if m == "sg13_lv_nmos" and nodes[1].startswith("d_"):
                nodes[1] = "d_b1_0"
                break
    tests.append(("duplicate pad gate", dup_gate))
    def open_tail(d):
        for i, (n, nodes, m, p) in enumerate(d):
            if m == "sg13_lv_nmos":
                nodes[2] = "floating_tail"
                d[i] = (n, nodes, m, p)
                break
    tests.append(("open tail", open_tail))
    def bulk(d):
        for i, (n, nodes, m, p) in enumerate(d):
            if m == "sg13_lv_pmos":
                nodes[3] = "vss"
                break
    tests.append(("pmos bulk vss", bulk))
    bad = []
    for name, fn in tests:
        if not mutated(fn):
            bad.append(name)
    print(f"selftest: {len(tests) - len(bad)}/{len(tests)} mutations rejected")
    if bad:
        print("NOT rejected:", bad)
        return 1
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all",
                    choices=["all", "build", "drc", "lvs", "pins"])
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    pdk = find_pdk()
    report = {}
    stages = (["build", "drc", "lvs", "pins"] if a.stage == "all"
              else [a.stage])
    rc = 0
    for st in stages:
        fn = {"build": build, "drc": drc, "lvs": lvs, "pins": pins}[st]
        try:
            res = build(pdk) if st == "build" else (
                pins() if st == "pins" else fn(pdk))
        except SystemExit:
            raise
        report[st] = res
        print(json.dumps({st: res}, indent=2)[:1800])
        if not res.get("ok", True):
            rc = 1
    (BUILD / "signoff.json").write_text(json.dumps(report, indent=2))
    return rc


if __name__ == "__main__":
    sys.exit(main())
